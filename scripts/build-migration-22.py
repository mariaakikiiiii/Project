"""Generate database/22-deposit-lifecycle-venues.sql from its readable template.
Same approach as build-safe-migrations.py: every constant DDL statement/module is
compiled separately inside ONE outer transaction, so the file runs in ordinary
SSMS mode and either fully applies or fully rolls back. No runtime input is used.
"""
from pathlib import Path
import re
ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / 'scripts/migration-bodies/22-deposit-lifecycle-venues.sql.txt'
OUT = ROOT / 'database/22-deposit-lifecycle-venues.sql'

def statements(text):
    start = 0; quoted = False; i = 0
    while i < len(text):
        if text[i] == "'":
            if quoted and i + 1 < len(text) and text[i + 1] == "'": i += 2; continue
            quoted = not quoted
        if text[i] == ';' and not quoted:
            value = text[start:i + 1].strip()
            if value: yield value
            start = i + 1
        i += 1
    if text[start:].strip(): yield text[start:].strip()

def execute(sql): return " EXEC(N'" + sql.replace("'", "''") + "');\n"

text = SRC.read_text()
batches = re.split(r'^GO\s*$', text, flags=re.M | re.I)
header = next(b for b in batches if 'BEGIN TRANSACTION;' in b and 'CREATE OR ALTER' not in b)
ddl = header.split('BEGIN TRANSACTION;', 1)[1]
ddl = '\n'.join(l for l in ddl.splitlines() if not l.lstrip().startswith('--'))
modules = [b.strip() for b in batches if re.search(r'^CREATE OR ALTER ', b, re.I | re.M)]
grants = re.findall(r'^GRANT EXECUTE ON .*?;', text, re.M)
if len(modules) != len(re.findall(r'^CREATE OR ALTER ', text, re.I | re.M)): raise SystemExit('module extraction mismatch')

out = '''-- GameOn migration 22: deposit lifecycle (attendance, disputes, host hold) + venue directory provenance.
-- Requires migration 20. Back up GameOn and stop the API first.
-- Run the WHOLE file in a NEW SSMS query (ordinary mode, SQLCMD Mode OFF) with your Windows/admin login.
-- One transaction: it either fully applies or changes nothing. It never deletes accounts, bookings or payments.
-- GENERATED by scripts/build-migration-22.py - edit the template, not this file.
USE GameOn;
GO
IF @@TRANCOUNT<>0 THROW 50002,'Open a fresh query with no active transaction.',1;
SET NOCOUNT ON; SET XACT_ABORT ON;
SET ANSI_NULLS ON; SET QUOTED_IDENTIFIER ON; SET ANSI_PADDING ON;
SET ANSI_WARNINGS ON; SET CONCAT_NULL_YIELDS_NULL ON; SET ARITHABORT ON; SET NUMERIC_ROUNDABORT OFF;
BEGIN TRY
 BEGIN TRANSACTION;
 IF NOT EXISTS(SELECT 1 FROM dbo.PlatformMigrations WHERE Version=20) THROW 50002,'Install migration 20 first.',1;
 IF EXISTS(SELECT 1 FROM dbo.PlatformMigrations WHERE Version=22) THROW 50002,'Migration 22 is already installed. Do not rerun it.',1;
 IF OBJECT_ID(N'dbo.VenueSubtypes',N'U') IS NULL OR COL_LENGTH(N'dbo.DepositBookings',N'RefundReference') IS NULL
  OR NOT EXISTS(SELECT 1 FROM sys.check_constraints WHERE name=N'CK_Deposit_State') THROW 50002,'Migration 18/20 schema is incomplete. Stop and report this message.',1;
 IF EXISTS(SELECT RefundReference FROM dbo.DepositBookings WHERE RefundReference IS NOT NULL GROUP BY RefundReference HAVING COUNT(*)>1)
  THROW 50002,'Duplicate refund references exist. Reconcile them before installing migration 22.',1;
'''
for sql in list(statements(ddl)) + modules + grants: out += execute(sql)
out += ''' INSERT dbo.PlatformMigrations(Version) VALUES(22);
 COMMIT;
 SELECT 'Migration 22 completed successfully' AS Result;
END TRY
BEGIN CATCH
 IF XACT_STATE()<>0 ROLLBACK;
 THROW;
END CATCH;
'''
OUT.write_text(out, newline='\r\n')
print(f'wrote {OUT} ({len(modules)} modules, {len(grants)} grants)')
