"""Generate guarded migrations from readable templates in scripts/migration-bodies/.
Usage: python scripts/build-migration.py   (rebuilds every migration listed below)

Same approach as build-safe-migrations.py: every constant DDL statement/module is
compiled separately inside ONE outer transaction, so each file runs in ordinary
SSMS mode and either fully applies or fully rolls back. No runtime input is used.
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]

MIGRATIONS = {
    22: dict(name='22-deposit-lifecycle-venues', prior=20,
             title='deposit lifecycle (attendance, disputes, host hold) + venue directory provenance.',
             guard=""" IF OBJECT_ID(N'dbo.VenueSubtypes',N'U') IS NULL OR COL_LENGTH(N'dbo.DepositBookings',N'RefundReference') IS NULL
  OR NOT EXISTS(SELECT 1 FROM sys.check_constraints WHERE name=N'CK_Deposit_State') THROW 50002,'Migration 18/20 schema is incomplete. Stop and report this message.',1;
 IF EXISTS(SELECT RefundReference FROM dbo.DepositBookings WHERE RefundReference IS NOT NULL GROUP BY RefundReference HAVING COUNT(*)>1)
  THROW 50002,'Duplicate refund references exist. Reconcile them before installing migration 22.',1;
"""),
    25: dict(name='25-wallet', prior=22,
             title='GameOn wallet (ledger, Whish top-ups, $1 wallet deposits, instant wallet refunds, withdrawals).',
             guard=""" IF NOT EXISTS(SELECT 1 FROM sys.check_constraints WHERE name=N'CK__DepositBo__Payme__2057CCD0')
  THROW 50002,'The deposit payment-method constraint is not the expected one. Stop and report this message.',1;
"""),
}


def statements(text):
    start = 0; quoted = False; i = 0
    while i < len(text):
        if text[i] == "'":
            if quoted and i + 1 < len(text) and text[i + 1] == "'": i += 2; continue
            quoted = not quoted
        if text[i] == ';' and not quoted:
            value = text[start:i + 1].strip()
            if value: yield value
            start = i + 1
        i += 1
    if text[start:].strip(): yield text[start:].strip()


def execute(sql): return " EXEC(N'" + sql.replace("'", "''") + "');\n"


def build(v, m):
    src = ROOT / f"scripts/migration-bodies/{m['name']}.sql.txt"
    out_path = ROOT / f"database/{m['name']}.sql"
    text = src.read_text(encoding='utf-8')
    batches = re.split(r'^GO\s*$', text, flags=re.M | re.I)
    header = next(b for b in batches if 'BEGIN TRANSACTION;' in b and 'CREATE OR ALTER' not in b)
    ddl = header.split('BEGIN TRANSACTION;', 1)[1]
    ddl = '\n'.join(l for l in ddl.splitlines() if not l.lstrip().startswith('--'))
    modules = [b.strip() for b in batches if re.search(r'^CREATE OR ALTER ', b, re.I | re.M)]
    grants = re.findall(r'^GRANT EXECUTE ON .*?;', text, re.M)
    if len(modules) != len(re.findall(r'^CREATE OR ALTER ', text, re.I | re.M)):
        raise SystemExit(f'{v}: module extraction mismatch')
    out = f"""-- GameOn migration {v}: {m['title']}
-- Requires migration {m['prior']}. Back up GameOn and stop the API first.
-- Run the WHOLE file in a NEW SSMS query (ordinary mode, SQLCMD Mode OFF) with your Windows/admin login.
-- One transaction: it either fully applies or changes nothing. It never deletes accounts, bookings or payments.
-- GENERATED by scripts/build-migration.py - edit the template, not this file.
USE GameOn;
GO
IF @@TRANCOUNT<>0 THROW 50002,'Open a fresh query with no active transaction.',1;
SET NOCOUNT ON; SET XACT_ABORT ON;
SET ANSI_NULLS ON; SET QUOTED_IDENTIFIER ON; SET ANSI_PADDING ON;
SET ANSI_WARNINGS ON; SET CONCAT_NULL_YIELDS_NULL ON; SET ARITHABORT ON; SET NUMERIC_ROUNDABORT OFF;
BEGIN TRY
 BEGIN TRANSACTION;
 IF NOT EXISTS(SELECT 1 FROM dbo.PlatformMigrations WHERE Version={m['prior']}) THROW 50002,'Install migration {m['prior']} first.',1;
 IF EXISTS(SELECT 1 FROM dbo.PlatformMigrations WHERE Version={v}) THROW 50002,'Migration {v} is already installed. Do not rerun it.',1;
""" + m['guard']
    for sql in list(statements(ddl)) + modules + grants: out += execute(sql)
    out += f""" INSERT dbo.PlatformMigrations(Version) VALUES({v});
 COMMIT;
 SELECT 'Migration {v} completed successfully' AS Result;
END TRY
BEGIN CATCH
 IF XACT_STATE()<>0 ROLLBACK;
 THROW;
END CATCH;
"""
    out_path.write_text(out, newline='\r\n', encoding='utf-8')
    print(f'wrote {out_path} ({len(modules)} modules, {len(grants)} grants)')


for version, spec in MIGRATIONS.items():
    build(version, spec)
